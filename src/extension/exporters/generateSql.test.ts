import { DatabaseSync } from 'node:sqlite';
import { expect, it } from 'vitest';
import { generateSql } from './generateSql';

const source = `
  Enum billing.state {
    ready
    "it's done"
  }
  Table billing.invoices {
    id int [pk, increment]
    tenant_id int [not null]
    status billing.state [default: 'ready']
    label varchar [default: 'it\\'s ready']
    indexes { (tenant_id, label) [unique] }
  }
  Table owners { id int [pk] }
  Table profiles { owner_id int [ref: - owners.id] }
  Table tags { id int [pk] }
  Ref: billing.invoices.id <> tags.id
  Ref tenant: billing.invoices.tenant_id > owners.id [delete: restrict, update: cascade]
  Ref diagram_only: billing.invoices.id > owners.id [inactive]
  records owners (id) { 99 }
`;

it('emits MySQL and MariaDB DDL with native enums, keys and index names', () => {
  const { sql } = generateSql(source, 'mysql');
  expect(sql).toContain('AUTO_INCREMENT');
  expect(sql).toContain("ENUM ('ready', 'it''s done')");
  expect(sql).toContain("DEFAULT 'it''s ready'");
  expect(sql).toMatch(/CREATE UNIQUE INDEX `dbml_index_\d+` ON `billing`\.`invoices`/);
  expect(sql).toContain('ON DELETE RESTRICT ON UPDATE CASCADE');
  expect(sql).not.toMatch(/diagram_only|INSERT INTO/);
});

it('emits Oracle identity DDL and reports unrepresentable foreign key actions', () => {
  const { sql, warnings } = generateSql(source, 'oracle');
  expect(sql).toContain('GENERATED BY DEFAULT AS IDENTITY');
  expect(sql).toContain(`NVARCHAR2(255) DEFAULT 'ready' CHECK ("status" IN ('ready', 'it''s done'))`);
  expect(sql).toMatch(/CREATE UNIQUE INDEX "dbml_index_\d+" ON/);
  expect(sql).not.toMatch(/ON DELETE RESTRICT|ON UPDATE CASCADE|diagram_only|INSERT INTO/);
  expect(warnings[0]).toContain('Oracle does not support ON UPDATE');
  expect(sql).not.toContain('TO PUBLIC;');
  expect(warnings[1]).toContain('cross-schema Oracle foreign keys');
});

it('emits SQL Server identities before constraints and maps RESTRICT to NO ACTION', () => {
  const { sql } = generateSql(source, 'mssql');
  expect(sql).toMatch(/\[id\] int IDENTITY\(1, 1\) PRIMARY KEY/i);
  expect(sql).toContain('ON DELETE NO ACTION ON UPDATE CASCADE');
  expect(sql).toMatch(/\nGO\b/);
  expect(sql).not.toMatch(/diagram_only|INSERT INTO/);
});

it('runs the SQLite script and enforces enum, one-to-one and junction constraints', () => {
  const { sql } = generateSql(source, 'sqlite');
  const db = new DatabaseSync(':memory:');
  try {
    db.exec(sql);
    expect(db.prepare('SELECT * FROM owners').all()).toHaveLength(0);
    db.exec('INSERT INTO owners VALUES (1); INSERT INTO tags VALUES (1); INSERT INTO profiles VALUES (1);');
    db.exec('INSERT INTO "billing.invoices" (tenant_id) VALUES (1);');
    expect(db.prepare('SELECT * FROM "billing.invoices"').get())
      .toEqual({ id: 1, tenant_id: 1, status: 'ready', label: "it's ready" });
    db.exec('INSERT INTO "billing.invoices_tags" VALUES (1, 1);');
    expect(() => db.exec('INSERT INTO "billing.invoices_tags" VALUES (1, 1);')).toThrow(/UNIQUE/);
    expect(() => db.exec('INSERT INTO profiles VALUES (1);')).toThrow(/UNIQUE/);
    expect(() => db.exec("INSERT INTO \"billing.invoices\" (tenant_id, status) VALUES (1, 'bad');")).toThrow(/CHECK/);
    expect(() => db.exec('INSERT INTO "billing.invoices" (tenant_id) VALUES (2);')).toThrow(/FOREIGN KEY/);
  } finally {
    db.close();
  }
});

it('emits executable SQLite DDL for composite and cyclic foreign keys', () => {
  const { sql } = generateSql(`
    Table parent {
      tenant int
      id int
      child int [ref: > child.id]
      indexes { (tenant, id) [pk] }
    }
    Table child { id int [pk]
      tenant int
      parent int
    }
    Ref: child.(tenant, parent) > parent.(tenant, id)
  `, 'sqlite');
  const db = new DatabaseSync(':memory:');
  try {
    db.exec(sql);
    db.exec('INSERT INTO parent (tenant, id) VALUES (1, 1); INSERT INTO child VALUES (2, 1, 1);');
    db.exec('UPDATE parent SET child = 2 WHERE tenant = 1 AND id = 1;');
    expect(() => db.exec('INSERT INTO child VALUES (3, 1, 2);')).toThrow(/FOREIGN KEY/);
    expect(db.prepare('PRAGMA foreign_key_check').all()).toEqual([]);
  } finally {
    db.close();
  }
});
