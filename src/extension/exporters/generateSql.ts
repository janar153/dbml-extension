import { isEndpointOneSide, ModelExporter, Parser, type NormalizedModel } from '@dbml/core';
import { projectParser, type DbmlProject } from '../dbmlProject';
import { renderSqlite } from './sqlite';
import type { SqlDialect } from './sqlDialects';

export function generateSql(source: string, dialect: SqlDialect, project?: DbmlProject): { sql: string; warnings: string[] } {
  const database = project
    ? projectParser(source, project, new Set()).parseDbmlProject(project.entry)
    : Parser.parse(source, 'dbmlv2');
  const model = database.normalize();
  // Records describe data. This export contains only the schema.
  model.records = {};
  prepareRefs(model);
  if (dialect === 'sqlite') return { sql: renderSqlite(model), warnings: [] };

  const warnings = prepareDialect(model, dialect);
  let ddl = ModelExporter.export(model, dialect).trimEnd();
  if (dialect === 'oracle') {
    // The upstream converter grants REFERENCES to every user for cross-schema foreign keys.
    const withoutPublicGrants = ddl.replace(/^GRANT REFERENCES ON "[^"\n]*"(?:\."[^"\n]*")? TO PUBLIC;\n/gm, '');
    if (withoutPublicGrants !== ddl) {
      warnings.push('For cross-schema Oracle foreign keys, grant REFERENCES only to the referencing schema before running the ALTER TABLE statements.');
      ddl = withoutPublicGrants;
    }
  }
  return { sql: dialect === 'postgres' ? postgresScript(ddl) : ddl + '\n', warnings };
}

function prepareDialect(model: NormalizedModel, dialect: Exclude<SqlDialect, 'sqlite'>): string[] {
  const warnings = new Set<string>();
  const escape = (value: string) => {
    const escaped = value.replaceAll("'", "''");
    return dialect === 'mysql' ? escaped.replaceAll('\\', '\\\\') : escaped;
  };
  for (const field of Object.values(model.fields)) {
    if (field.dbdefault?.type === 'string') {
      field.dbdefault.value = escape(String(field.dbdefault.value));
    }
    if (dialect === 'mysql' && field.note) field.note = field.note.replaceAll('\\', '\\\\');
    if (dialect === 'mssql' && field.increment && !field.enumId) {
      // IDENTITY belongs before column constraints.
      field.type.type_name += ' IDENTITY(1, 1)';
      field.increment = false;
    }
    if (dialect === 'oracle') {
      const type = field.type.type_name;
      if (/^varchar2?$/i.test(type)) field.type.type_name = 'VARCHAR2(255)';
      else if (/^bigint$/i.test(type)) field.type.type_name = 'NUMBER(19)';
      else if (/^text$/i.test(type)) field.type.type_name = 'CLOB';
      if (field.increment && !field.enumId) {
        field.type.type_name += ' GENERATED BY DEFAULT AS IDENTITY';
        field.increment = false;
        field.dbdefault = undefined;
      }
    }
  }
  for (const value of Object.values(model.enumValues)) {
    value.name = escape(value.name);
  }
  if (dialect === 'mysql') {
    for (const table of Object.values(model.tables)) {
      if (table.note) table.note = table.note.replaceAll('\\', '\\\\');
    }
  }
  if (dialect === 'mssql') {
    for (const ref of Object.values(model.refs)) {
      if (ref.onDelete?.toLowerCase() === 'restrict') ref.onDelete = 'no action';
      if (ref.onUpdate?.toLowerCase() === 'restrict') ref.onUpdate = 'no action';
    }
    for (const table of Object.values(model.tables)) {
      table.indexIds = (table.indexIds as number[]).filter((id) => {
        const index = model.indexes[id]!;
        if (!index.columnIds.some((columnId) => model.indexColumns[columnId]!.type === 'expression')) return true;
        warnings.add('SQL Server requires computed columns for expression indexes. The exported script omits those indexes.');
        return false;
      });
    }
  }
  if (dialect === 'oracle' || dialect === 'mysql') nameIndexes(model);
  if (dialect === 'oracle') {
    let checkId = -1;
    for (const field of Object.values(model.fields)) {
      if (!field.enumId) continue;
      const values = model.enums[field.enumId]!.valueIds.map((id) => `'${model.enumValues[id]!.name}'`);
      field.enumId = null;
      field.type.type_name = 'NVARCHAR2(255)';
      const id = checkId--;
      model.checks[id] = {
        id, tableId: field.tableId, columnId: field.id, name: '',
        expression: `"${field.name.replaceAll('"', '""')}" IN (${values.join(', ')})`, injectedPartialId: null,
      };
      field.checkIds.push(id);
    }
    for (const ref of Object.values(model.refs)) {
      if (ref.inactive) continue;
      if (ref.onUpdate && ref.onUpdate.toLowerCase() !== 'no action') {
        warnings.add('Oracle does not support ON UPDATE foreign key actions. Review the exported foreign keys.');
      }
      if (ref.onDelete && !['cascade', 'set null'].includes(ref.onDelete.toLowerCase())) {
        if (!['restrict', 'no action'].includes(ref.onDelete.toLowerCase())) {
          warnings.add('Oracle does not support ON DELETE SET DEFAULT. The exported foreign key uses the default behavior.');
        }
        ref.onDelete = undefined;
      }
    }
  }
  return [...warnings];
}

function nameIndexes(model: NormalizedModel): void {
  // Oracle requires a name, and the upstream MySQL fallback is malformed for named schemas.
  const indexes = Object.values(model.indexes).filter((index) => !index.pk);
  const names = new Set(indexes.map((index) => index.name?.toLowerCase()));
  let next = 1;
  for (const index of indexes) {
    if (index.name) continue;
    let name: string;
    do { name = 'dbml_index_' + next++; } while (names.has(name));
    index.name = name;
  }
}

function postgresScript(ddl: string): string {
  return [
    'BEGIN;',
    'SET LOCAL search_path TO public;',
    'SET LOCAL standard_conforming_strings TO on;',
    '',
    ddl.replace(/^CREATE SCHEMA "public";$/m, 'CREATE SCHEMA IF NOT EXISTS "public";'),
    '',
    'COMMIT;',
    '',
  ].join('\n');
}

function prepareRefs(model: NormalizedModel): void {
  let nextIndexId = -1;
  let nextColumnId = -1;
  for (const schema of Object.values(model.schemas)) {
    const activeRefIds = (schema.refIds as number[]).filter((id) => !model.refs[id]!.inactive);
    schema.refIds = activeRefIds;
    for (const id of activeRefIds) {
      const [target, foreign] = model.refs[id]!.endpointIds.map((endpointId) => model.endpoints[endpointId]);
      if (!target || !foreign || !isEndpointOneSide(target.relation) || !isEndpointOneSide(foreign.relation)) continue;

      // The parser puts the FK endpoint second for one-to-one refs, including inline refs.
      // Add uniqueness to that side so the generated DDL enforces the declared cardinality.
      const fields = foreign.fieldIds.map((fieldId) => model.fields[fieldId]!);
      if (fields.some((field) => field.unique || field.pk)) continue;
      const table = model.tables[fields[0]!.tableId]!;
      const names = new Set(fields.map((field) => field.name));
      const hasUniqueKey = table.indexIds.some((indexId) => {
        const index = model.indexes[indexId]!;
        return (index.unique || index.pk) && index.columnIds.every((columnId) => {
          const column = model.indexColumns[columnId]!;
          return column.type !== 'expression' && names.has(column.value);
        });
      });
      if (hasUniqueKey) continue;

      const indexId = nextIndexId--;
      const columnIds = fields.map((field) => {
        const columnId = nextColumnId--;
        model.indexColumns[columnId] = { id: columnId, indexId, type: 'column', value: field.name };
        return columnId;
      });
      model.indexes[indexId] = {
        id: indexId, tableId: table.id, columnIds, unique: true, pk: '', name: null, note: null, type: null,
      };
      table.indexIds.push(indexId);
    }
  }
}
